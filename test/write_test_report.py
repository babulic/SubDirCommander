#!/usr/bin/env python3
"""Write the current official SubDirCommander test result as Markdown.

Called from the EXIT trap of every supported test entry point.  It records a
failure or an adapter SKIP too, so TEST_REPORT_SUB39.md can never retain an
old PASS after a later failed run.
"""

from __future__ import annotations

import argparse
import re
import subprocess
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "TEST_REPORT_SUB39.md"
HISTORY_DIR = ROOT / "test" / "reports"


def git_commit() -> str:
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, text=True
        ).strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def outcome(status: int) -> str:
    if status == 0:
        return "PASS"
    if status == 77:
        return "SKIP"
    return "FAIL"


def scope(suite: str, target: str | None) -> list[str]:
    if suite == "runall":
        return [
            "`test/verify_artifacts.py` — source/artifact, helper and D64 checks.",
            "`test/verify_device_matrix.py` — published capability matrix checks.",
            "BASIC VICE scenarios `t4` through `t15`.",
            "ML VICE scenarios `m1`, `m2`, `m4` through `m8`.",
        ]
    if suite == "scenario":
        return [
            "Fresh deterministic D64 fixtures for one scenario.",
            f"VICE scenario `{target}`.",
        ]
    return [
        f"Device matrix target `{target}`.",
        "A firmware/emulator adapter is required except for `pi1541-d64`.",
    ]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--suite", choices=("runall", "scenario", "device"), required=True)
    parser.add_argument("--status", type=int, required=True)
    parser.add_argument("--target")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--no-history", action="store_true")
    args = parser.parse_args()

    moment = datetime.now(ZoneInfo("Europe/Bratislava"))
    now = moment.strftime("%Y-%m-%d %H:%M:%S %Z")
    result = outcome(args.status)
    target = args.target or "—"
    body = [
        "# SubDirCommander 3.9 — latest automated test report",
        "",
        "> This file is regenerated by the official test runners. It records the",
        "> most recent run, including FAIL and adapter SKIP results.",
        "",
        f"- **Generated:** {now}",
        f"- **Git HEAD when report was written:** `{git_commit()}`",
        f"- **Runner:** `{args.suite}`",
        f"- **Target:** `{target}`",
        f"- **Exit status:** `{args.status}`",
        f"- **Result:** **{result}**",
        "",
        "## Executed scope",
        "",
    ]
    body.extend(f"- {item}" for item in scope(args.suite, args.target))
    body += [
        "",
        "## Interpretation",
        "",
        "- `PASS` means this runner completed with exit status 0.",
        "- `FAIL` means this runner exited nonzero other than 77.",
        "- `SKIP` (77) means a device adapter was not supplied; it is never a pass.",
        "",
        "Device-specific firmware coverage is described in `test/DEVICE_MATRIX.md`.",
        "Open review items and architectural limits are in `CODE_REVIEW_CODEX_02.md`.",
    ]
    contents = "\n".join(body) + "\n"
    args.output.write_text(contents, encoding="utf-8")
    if not args.no_history:
        HISTORY_DIR.mkdir(exist_ok=True)
        label = re.sub(r"[^A-Za-z0-9._-]+", "_", args.target or "all")
        stamp = moment.strftime("%Y-%m-%d_%H-%M-%S-%f")
        result_label = result if args.status == 0 else f"{result}-{args.status}"
        stem = f"{stamp}__{args.suite}__{label}__{result_label}"
        attempt = 1
        while True:
            suffix = "" if attempt == 1 else f"__{attempt}"
            history = HISTORY_DIR / f"{stem}{suffix}.md"
            try:
                # Exclusive creation makes parallel test invocations safe too.
                with history.open("x", encoding="utf-8") as report:
                    report.write(contents)
                break
            except FileExistsError:
                attempt += 1


if __name__ == "__main__":
    main()
